import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import type { FieldComparison, VerificationReport } from '../types';

export function exportVerificationReportPdf(report: VerificationReport): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const comparisons = JSON.parse(report.comparison_json || '[]') as FieldComparison[];
  const missingFields = JSON.parse(report.missing_fields_json || '[]') as string[];
  const steps = JSON.parse(report.recommended_steps_json || '[]') as string[];

  // Header band
  doc.setFillColor(23, 75, 56);
  doc.rect(0, 0, 210, 28, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('LANDTRACE AI — VERIFICATION REPORT', 14, 13);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text('AI-Powered Land Record Intelligence & Fraud Detection (Advisory Record Only)', 14, 20);

  // Meta box
  doc.setTextColor(32, 42, 37);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text(`Report Reference: ${report.report_ref}`, 14, 38);
  doc.text(`Parcel ID: ${report.parcel_id}`, 115, 38);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(`Survey Number: ${report.survey_number || 'N/A'}`, 14, 44);
  doc.text(`District / Village: ${report.district_name || ''} · ${report.village || ''}`, 115, 44);
  doc.text(`Registered Owner: ${report.current_owner || 'N/A'}`, 14, 50);
  doc.text(`Area: ${report.land_area_display || 'N/A'}`, 115, 50);
  doc.text(`Risk Score: ${report.risk_score}/100 (${report.risk_category})`, 14, 56);
  doc.text(`Audit Entry ID: ${report.audit_entry_id || 'N/A'}`, 115, 56);
  doc.text(`Source Document: ${report.filename || report.doc_ref || 'Synthetic Record'}`, 14, 62);
  doc.text(`Generated: ${new Date(report.created_at).toLocaleString()}`, 115, 62);

  // Comparison table
  autoTable(doc, {
    startY: 70,
    head: [['Field', 'Registry Database Value', 'Document Extracted Value', 'Status', 'Observation']],
    body: comparisons.map((c) => [
      c.label,
      c.database_value || '—',
      c.extracted_value || '—',
      c.status,
      c.note || '',
    ]),
    headStyles: { fillColor: [23, 75, 56], textColor: 255, fontSize: 8.5 },
    bodyStyles: { fontSize: 8, textColor: [32, 42, 37] },
    alternateRowStyles: { fillColor: [248, 249, 245] },
    margin: { left: 14, right: 14 },
  });

  const finalY = ((doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? 120) + 10;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('AI Evidence-Based Explanation', 14, finalY);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  const splitExpl = doc.splitTextToSize(report.ai_explanation || 'No explanation recorded.', 182);
  doc.text(splitExpl, 14, finalY + 6);

  let nextY = finalY + 6 + splitExpl.length * 4.5 + 6;
  if (missingFields.length > 0) {
    doc.setFont('helvetica', 'bold');
    doc.text(`Missing Fields: ${missingFields.join(', ')}`, 14, nextY);
    nextY += 8;
  }

  doc.setFont('helvetica', 'bold');
  doc.text('Recommended Verification Steps', 14, nextY);
  doc.setFont('helvetica', 'normal');
  nextY += 6;
  steps.forEach((step, idx) => {
    const lines = doc.splitTextToSize(`${idx + 1}. ${step}`, 182);
    doc.text(lines, 14, nextY);
    nextY += lines.length * 4.5 + 2;
  });

  // Disclaimer footer
  doc.setDrawColor(226, 230, 220);
  doc.line(14, 276, 196, 276);
  doc.setFontSize(7.5);
  doc.setTextColor(92, 104, 97);
  doc.text(
    'DISCLAIMER: Synthetic demo dataset. Advisory intelligence generated by LandTrace AI does not constitute legal proof of ownership or official government registry certification.',
    14,
    282,
    { maxWidth: 182 }
  );

  doc.save(`${report.report_ref}.pdf`);
}
